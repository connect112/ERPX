"""Build archive_host.sh and pentrix-op-archive-old-dumps.json (the SSM command document that archives the four approved dumps).

Writes files only. Nothing is registered with AWS and nothing runs. Run: python build_archive_doc.py

  --rehearsal   also writes rehearsal/ (NOT committed): the same script and Python with the approved table replaced by test
                values, so the real shell pipeline can be run against a local scratch bucket. See tests / the README.
"""
import base64
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).parent


def joined_python(delete_source, archive_source):
    """The code the container runs: the deletion module's helpers (without its main) followed by the archive module."""
    head = delete_source.split('if __name__ == "__main__":')[0]
    return head.rstrip() + "\n\n\n" + archive_source


HOST_SCRIPT = r'''#!/usr/bin/env bash
# Generated by build_archive_doc.py from the approved table in delete_old_dumps.py. Runs on the ERPX host as root;
# the Python (written to $PY by the SSM document) runs inside the erpx_api container, which holds the MinIO credentials.
# S3 access is the instance role's: it can put and get in the backup bucket and can not delete anything.
# Usage: archive_host.sh plan|archive|verify [confirmation]
set -euo pipefail
MODE="${1:-plan}"; CONFIRM="${2:-}"
B=pentrix-erpx-backups-373384939117
P=archive/inapp-dumps-2026-10-08-to-11
PY="${PY:-/tmp/ro_archive.py}"
export AWS_CONFIG_FILE="${AWS_CONFIG_FILE:-/opt/backups/offsite/aws_config}" AWS_DEFAULT_REGION=us-east-1
WORK=$(mktemp -d); trap 'rm -rf "$WORK"' EXIT

# id|object key|date|approved sha256 (written from APPROVED, never typed twice)
FILES=(
@@FILES@@
)

case "$MODE" in plan|archive|verify) ;; *) echo "ABORT: unknown mode $MODE"; exit 2 ;; esac
if [ "$MODE" = "archive" ] && [ "$CONFIRM" != "ARCHIVE-4-OLD-DUMPS" ]; then
  echo "ABORT: the confirmation phrase is missing or wrong. Nothing was written."; exit 3
fi
echo "mode: $MODE"

facts() {
  docker exec shared_postgres psql -U postgres -d erpx -tA -c "@@FACTS_SQL@@"
}
pyrun() {   # pyrun <mode> [args]: the container's Python, with the inputs it needs in its environment
  local mode="$1"; shift
  nice -n 19 ionice -c3 docker exec -i -e MODE="$mode" -e DATA_JSON="${FACTS:-}" -e METAS_JSON="${METAS:-}" \
    -e RESULTS_JSON="${RESULTS:-}" erpx_api python - "$@" < "$PY"
}
s3size() { aws s3api head-object --bucket "$B" --key "$1" --query ContentLength --output text; }
s3has()  { aws s3api head-object --bucket "$B" --key "$1" > /dev/null 2>&1; }

echo "== gate 1: the off-server backup is fresh and verified =="
STATUS=$(cat /opt/backups/offsite/last_status.json); echo "$STATUS"
echo "$STATUS" | grep -q '"ok":true' || { echo "ABORT: the last off-server backup is not green."; exit 4; }
AT=$(echo "$STATUS" | sed -n 's/.*"at":"\([^"]*\)".*/\1/p')
AGE=$(( $(date -u +%s) - $(date -u -d "$AT" +%s) ))
[ "$AGE" -lt 100800 ] || { echo "ABORT: the last off-server backup is older than 28 hours."; exit 4; }
STAMP=$(echo "$STATUS" | sed -n 's/.*"stamp":"\([^"]*\)".*/\1/p')
s3has "daily/$STAMP/SHA256SUMS" || { echo "ABORT: the S3 backup for $STAMP has no SHA256SUMS."; exit 4; }
echo "S3 backup $STAMP is complete"

echo "== gate 2: facts from the database (read-only) =="
FACTS=$(facts)

if [ "$MODE" = "plan" ]; then
  echo "== plan: gates, size estimate and cost (writes nothing) =="
  pyrun plan
  if s3has "$P/manifest.json"; then echo "note: an archive manifest already exists in S3 (archive mode would do nothing; use verify)"; fi
  exit 0
fi

if [ "$MODE" = "archive" ]; then
  if s3has "$P/manifest.json"; then echo "Already archived: $P/manifest.json exists. Run Mode=verify. Nothing was written."; exit 0; fi
  echo "== gate 3: the originals match their approved checksums (reads only) =="
  pyrun plan
  METAS='{}'
  for entry in "${FILES[@]}"; do
    IFS='|' read -r id key day sha <<< "$entry"
    dest="s3://$B/$P/${day}_${id}.sql.gz"
    echo "== archiving $key -> $dest =="
    if ! pyrun stream "$key" 2> "$WORK/$id.err" | aws s3 cp - "$dest" --expected-size 3000000000 --only-show-errors; then
      echo "ABORT: streaming $key to S3 failed. Nothing was deleted and no manifest was written. The container said:"
      cat "$WORK/$id.err" || true
      exit 5
    fi
    META=$(grep '^META|' "$WORK/$id.err" | sed 's/^META|//' || true)
    [ -n "$META" ] || { echo "ABORT: no checksums reported for $key"; cat "$WORK/$id.err"; exit 5; }
    METAS=$(python3 -c 'import json,sys; m=json.loads(sys.argv[1]); m[sys.argv[2]]=json.loads(sys.argv[3]); print(json.dumps(m))' "$METAS" "$id" "$META")
    ORIG=$(python3 -c 'import json,sys; print(json.loads(sys.argv[1])["original_sha256"])' "$META")
    GZSIZE=$(python3 -c 'import json,sys; print(json.loads(sys.argv[1])["gz_size"])' "$META")
    [ "$ORIG" = "$sha" ] || { echo "ABORT: the bytes read for $key do not hash to the approved value"; exit 5; }
    [ "$(s3size "$P/${day}_${id}.sql.gz")" = "$GZSIZE" ] || { echo "ABORT: the S3 object for $id is not the size that was sent"; exit 5; }
    echo "uploaded $GZSIZE bytes; original sha256 matches"
  done
  export METAS
  pyrun manifest | aws s3 cp - "s3://$B/$P/manifest.json" --only-show-errors
  pyrun readme   | aws s3 cp - "s3://$B/$P/README.txt" --only-show-errors
  echo "ARCHIVED. Next: run Mode=verify (it reads every copy back from S3). Nothing was deleted anywhere."
  exit 0
fi

# verify: read every copy back from S3, then write the marker the deletion document requires
echo "== verify: reading the archive back from S3 =="
s3has "$P/manifest.json" || { echo "ABORT: no manifest in S3; run archive mode first."; exit 6; }
aws s3 cp "s3://$B/$P/manifest.json" "$WORK/manifest.json" --only-show-errors
RESULTS='{}'
for entry in "${FILES[@]}"; do
  IFS='|' read -r id key day sha <<< "$entry"
  OBJ="$P/${day}_${id}.sql.gz"
  WANT=$(python3 -c 'import json,sys; m=json.load(open(sys.argv[1])); f=[x for x in m["files"] if x["job_id"]==sys.argv[2]][0]; print(f["archive_size_bytes"], f["archive_sha256"], f["original_sha256"])' "$WORK/manifest.json" "$id")
  read -r WANT_SIZE WANT_GZ WANT_ORIG <<< "$WANT"
  SIZE=$(s3size "$OBJ")
  aws s3 cp "s3://$B/$OBJ" - --only-show-errors | tee >(sha256sum | cut -d' ' -f1 > "$WORK/$id.gz.sha") | gunzip | sha256sum | cut -d' ' -f1 > "$WORK/$id.orig.sha"
  for _ in $(seq 1 60); do [ -s "$WORK/$id.gz.sha" ] && break; sleep 1; done
  GZ_GOT=$(cat "$WORK/$id.gz.sha"); ORIG_GOT=$(cat "$WORK/$id.orig.sha")
  s_ok=false; g_ok=false; o_ok=false
  [ "$SIZE" = "$WANT_SIZE" ] && s_ok=true
  [ "$GZ_GOT" = "$WANT_GZ" ] && g_ok=true
  { [ "$ORIG_GOT" = "$WANT_ORIG" ] && [ "$ORIG_GOT" = "$sha" ]; } && o_ok=true
  echo "$day $id: size $SIZE ($s_ok), archive sha256 ($g_ok), decompressed sha256 equals the original ($o_ok)"
  RESULTS=$(python3 -c 'import json,sys; r=json.loads(sys.argv[1]); r[sys.argv[2]]={"archive_size_ok": sys.argv[3]=="true", "archive_sha256_ok": sys.argv[4]=="true", "original_sha256_ok": sys.argv[5]=="true", "archive_size": int(sys.argv[6]), "archive_sha256": sys.argv[7]}; print(json.dumps(r))' "$RESULTS" "$id" "$s_ok" "$g_ok" "$o_ok" "$SIZE" "$GZ_GOT")
done
export RESULTS
pyrun marker > "$WORK/VERIFIED.json"
if grep -q '"all_verified": true' "$WORK/VERIFIED.json"; then
  aws s3 cp "$WORK/VERIFIED.json" "s3://$B/$P/VERIFIED.json" --only-show-errors
  echo "VERIFIED: all four archive copies read back from S3 and matched. VERIFIED.json written. Nothing was deleted anywhere."
else
  cat "$WORK/VERIFIED.json"; echo "NOT VERIFIED: no marker written. The deletion document will refuse to run."; exit 7
fi
'''


def facts_sql(ids):
    return (
        "select json_build_object("
        f"'rows', (select coalesce(json_agg(json_build_object('id', id, 'status', status::text, 'size_bytes', size_bytes, "
        f"'sha256', sha256, 'storage_key', storage_key, 'started_at', started_at)), '[]'::json) from backup_jobs where id::text in ({ids})), "
        "'newest', (select coalesce(json_agg(t), '[]'::json) from (select id, status::text as status, size_bytes, storage_key, "
        "started_at from backup_jobs where status = 'completed' order by started_at desc limit 3) t))"
    )


def build(approved, delete_source, archive_source, out_dir, tag=""):
    ids = ",".join(f"'{a[0]}'" for a in approved)
    files = "\n".join(f'  "{a[0]}|{a[1]}|{a[4]}|{a[3]}"' for a in approved)
    script = HOST_SCRIPT.replace("@@FILES@@", files).replace("@@FACTS_SQL@@", facts_sql(ids))
    python_source = joined_python(delete_source, archive_source)
    py_b64 = base64.b64encode(python_source.encode()).decode()
    sh_b64 = base64.b64encode(script.encode()).decode()
    commands = [
        "set -euo pipefail",
        "MODE='{{ Mode }}'",
        "CONFIRM='{{ Confirm }}'",
        f"printf '%s' '{py_b64}' | base64 -d > /tmp/ro_archive.py",
        f"printf '%s' '{sh_b64}' | base64 -d > /tmp/ro_archive.sh",
        'RC=0; bash /tmp/ro_archive.sh "$MODE" "$CONFIRM" || RC=$?',
        "rm -f /tmp/ro_archive.py /tmp/ro_archive.sh",
        'exit "$RC"',
    ]
    doc = {
        "schemaVersion": "2.2",
        "description": "Archives the four approved in-app dumps (8-11 Oct 2026) to S3 as gzip with a manifest, and verifies them by "
                       "reading them back. Never deletes or changes anything in MinIO. Default Mode=plan writes nothing.",
        "parameters": {
            "Mode": {"type": "String", "description": "plan (default, writes nothing), archive (writes to S3), or verify (reads back, writes the marker).",
                     "default": "plan", "allowedValues": ["plan", "archive", "verify"]},
            "Confirm": {"type": "String", "description": "For Mode=archive only: type ARCHIVE-4-OLD-DUMPS",
                        "default": "", "allowedPattern": "^[A-Z0-9-]{0,40}$"},
        },
        "mainSteps": [{"action": "aws:runShellScript", "name": "archiveOldDumps",
                       "inputs": {"runCommand": commands, "timeoutSeconds": "5400"}}],
    }
    out_dir.mkdir(exist_ok=True)
    (out_dir / f"archive_host{tag}.sh").write_text(script, encoding="utf-8", newline="\n")
    (out_dir / f"archive_container{tag}.py").write_text(python_source, encoding="utf-8", newline="\n")
    (out_dir / f"pentrix-op-archive-old-dumps{tag}.json").write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8", newline="\n")
    return doc


if __name__ == "__main__":
    delete_source = (HERE / "delete_old_dumps.py").read_text(encoding="utf-8").replace("\r\n", "\n")
    archive_source = (HERE / "archive_old_dumps.py").read_text(encoding="utf-8").replace("\r\n", "\n")
    namespace = {}
    exec(compile(delete_source.split("class MinioStore")[0], "delete_old_dumps", "exec"), namespace)
    doc = build(namespace["APPROVED"], delete_source, archive_source, HERE)
    print("wrote archive_host.sh, archive_container.py, pentrix-op-archive-old-dumps.json;",
          len(json.dumps(doc)), "bytes (SSM limit 64 KB)")
